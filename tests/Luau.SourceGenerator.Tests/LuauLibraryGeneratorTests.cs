    [Fact]
    public void AsyncReturnShapesUseOneValueTaskCallbackPathAndCompile()
    {
        const string source = """
using System.Threading.Tasks;
using Luau;

[LuauLibrary("async")]
public partial class AsyncApi
{
    [LuauMember] public Task TaskOnly() => Task.CompletedTask;
    [LuauMember] public Task<int> TaskValue() => Task.FromResult(1);
    [LuauMember] public ValueTask ValueTaskOnly() => ValueTask.CompletedTask;
    [LuauMember] public static ValueTask<string> ValueTaskValue() => ValueTask.FromResult("ok");
}
""";

        var result = RunGenerator(CreateCompilation(source), out var outputCompilation);

        Assert.Empty(result.Diagnostics);
        AssertNoErrors(outputCompilation);
        var generated = Assert.Single(result.GeneratedSources).SourceText.ToString();
        Assert.Equal(4, Count(generated, "CreateAsyncFunction("));
        Assert.Contains("await this.TaskOnly();", generated, StringComparison.Ordinal);
        Assert.Contains("var result = await this.TaskValue();", generated, StringComparison.Ordinal);
        Assert.Contains("await this.ValueTaskOnly();", generated, StringComparison.Ordinal);
        Assert.Contains(
            "var result = await global::AsyncApi.ValueTaskValue();",
            generated,
            StringComparison.Ordinal);
        Assert.Equal(2, Count(generated, "context.Return(result);"));
    }

