    static CSharpCompilation CreateCompilation(string source)
    {
        var apiTree = CSharpSyntaxTree.ParseText(ApiSource, ParseOptions, @"C:\probe\LuauApi.cs");
        var consumerTree = CSharpSyntaxTree.ParseText(source, ParseOptions, ConsumerPath);
        return CSharpCompilation.Create(
            "LuauConsumer",
            [apiTree, consumerTree],
            PlatformReferences,
            new CSharpCompilationOptions(
                OutputKind.DynamicallyLinkedLibrary,
                allowUnsafe: true,
                nullableContextOptions: NullableContextOptions.Enable));
    }

    static GeneratorRunResult RunGenerator(
        CSharpCompilation compilation,
        out Compilation outputCompilation)
    {
        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            [new LuauLibraryGenerator().AsSourceGenerator()],
            parseOptions: ParseOptions);

        driver = driver.RunGeneratorsAndUpdateCompilation(
            compilation,
            out outputCompilation,
            out var generatorDiagnostics);

        Assert.Empty(generatorDiagnostics.Where(
            diagnostic => diagnostic.Severity == DiagnosticSeverity.Error &&
                          diagnostic.Id == "CS8785"));
        return driver.GetRunResult().Results.Single();
    }

    static void AssertNoErrors(Compilation compilation)
    {
        var errors = compilation.GetDiagnostics()
            .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
            .Select(diagnostic => diagnostic.ToString())
            .ToArray();

        Assert.True(errors.Length == 0, string.Join(Environment.NewLine, errors));
    }

    static string Normalize(string source) =>
        source.Replace("\r\n", "\n", StringComparison.Ordinal).Trim();

    static int Count(string source, string value)
    {
        var count = 0;
        var index = 0;
        while ((index = source.IndexOf(value, index, StringComparison.Ordinal)) >= 0)
        {
            count++;
            index += value.Length;
        }

        return count;
    }

    static bool IsManagedAssembly(string path)
    {
        using var stream = File.OpenRead(path);
        using var reader = new PEReader(stream);
        return reader.HasMetadata;
    }
